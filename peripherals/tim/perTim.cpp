void TIM::Enable()
{
    CHECK_STATUS();
    MainOutputEnable();
    ctx.timReg_p->CR1 |= TIM_CR1_CEN;
    ChangeMode(Mode::RUN);
}

void TIM::Disable()
{
    CHECK_STATUS();
    ctx.timReg_p->CR1 &= ~TIM_CR1_CEN;
    ChangeMode(Mode::OFF);
}

Exec TIM::SetFrequency(uint32 freqHz)
{
    ASSERT(ctx.timReg_p != nullptr, "TIM NOT INITIALIZED");
    ASSERT(freqHz > 0, "TIM FREQUENCY");

    uint16 psc;
    uint32 arr;
    uint32 actualFreqHz;

    CHECK_EXEC(CalcTimebase(freqHz, &psc, &arr, &actualFreqHz));

    ctx.timReg_p->PSC = psc;
    ctx.timReg_p->ARR = arr;

    ctx.prescaler = psc;
    ctx.autoReload = arr;
    ctx.freqHz = actualFreqHz;
    ctx.config.freqHz = freqHz;

    // Recalculate all compare registers to preserve duty cycle.
    for (uint8 ch = 0; ch < (uint8)Channel::count; ch++) {
        if (ctx.channel[ch].configured) ApplyDuty((Channel)ch);
    }

    // PSC is shadowed and becomes active after update event.
    ctx.timReg_p->EGR = TIM_EGR_UG;
    ctx.timReg_p->SR &= ~TIM_SR_UIF;

    return Exec::OK;
}

Exec TIM::SetDuty(Channel channel, uint16 dutyPermille)
{
    CHECK_STATUS();
    ASSERT(channel != Channel::none, "PWM CHANNEL");
    ASSERT(IsChannelSupported(channel), "PWM CHANNEL NOT SUPPORTED");
    ASSERT(dutyPermille <= DUTY_MAX_PERMILLE, "PWM DUTY");

    uint8 ch = (uint8)channel;
    ASSERT(ctx.channel[ch].configured, "PWM CHANNEL NOT CONFIGURED");

    ctx.channel[ch].dutyPermille = dutyPermille;
    ctx.channel[ch].config.dutyPermille = dutyPermille;
    ApplyDuty(channel);

    return Exec::OK;
}

