uint32 TIM::CalcTimerClockHz()
{
    uint32 pclkHz = hal::clk::PerClkGetFreqHz(ctx.perId);
    if (pclkHz == 0) return 0;

    // STM32 timer kernel clock is 2 x PCLK when the corresponding APB prescaler is not DIV1.
    bool apbDiv1;

    if (ctx.config.timNum == Num::TIM_2) {
        apbDiv1 = (REG_RCC->CFGR.bit.PRE1 < 4);
    }
    else {
        apbDiv1 = (REG_RCC->CFGR.bit.PRE2 < 4);
    }

    return apbDiv1 ? pclkHz : (pclkHz * 2U);
}

Exec TIM::CalcTimebase(uint32 freqHz, uint16* psc_p, uint32* arr_p, uint32* actualFreqHz_p)
{
    ASSERT(psc_p != nullptr, "PSC PTR");
    ASSERT(arr_p != nullptr, "ARR PTR");
    ASSERT(actualFreqHz_p != nullptr, "FREQ PTR");

    ctx.timerClkHz = CalcTimerClockHz();
    ASSERT(ctx.timerClkHz > 0, "TIM CLOCK");
    ASSERT(freqHz <= ctx.timerClkHz, "TIM FREQUENCY TOO HIGH");

    const uint64 arrMax = (ctx.config.timNum == Num::TIM_2) ? ARR_MAX_32BIT : ARR_MAX_16BIT;
    const uint64 timerClk = ctx.timerClkHz;

    // Select the smallest prescaler that keeps ARR in range, maximizing timer resolution.
    uint64 totalTicks = (timerClk + (freqHz / 2U)) / freqHz;
    if (totalTicks == 0) totalTicks = 1;

    uint64 prescalerDiv = (totalTicks + arrMax) / (arrMax + 1ULL); // ceil(totalTicks/(ARRmax+1))
    if (prescalerDiv == 0) prescalerDiv = 1;
    ASSERT(prescalerDiv <= ((uint64)PSC_MAX + 1ULL), "TIM FREQUENCY TOO LOW");

    uint64 ticksPerPeriod = (timerClk + ((prescalerDiv * freqHz) / 2ULL)) / (prescalerDiv * freqHz);
    if (ticksPerPeriod == 0) ticksPerPeriod = 1;
    if (ticksPerPeriod > (arrMax + 1ULL)) ticksPerPeriod = arrMax + 1ULL;

    *psc_p = (uint16)(prescalerDiv - 1ULL);
    *arr_p = (uint32)(ticksPerPeriod - 1ULL);

    uint64 denom = prescalerDiv * ticksPerPeriod;
    *actualFreqHz_p = (uint32)(timerClk / denom);

    return Exec::OK;
}

void TIM::ApplyDuty(Channel channel)
{
    uint8 ch = (uint8)channel;
    volatile uint32* ccr_p = GetCcrReg(channel);
    if (ccr_p == nullptr) return;

    // PWM mode 1: CCR = ARR+1 gives constant active level (true 100%).
    uint64 periodTicks = (uint64)ctx.autoReload + 1ULL;
    uint64 compare = (periodTicks * ctx.channel[ch].dutyPermille + (DUTY_MAX_PERMILLE / 2U)) / DUTY_MAX_PERMILLE;

    *ccr_p = (uint32)compare;
}

bool TIM::IsChannelSupported(Channel channel)
{
    if (channel == Channel::none) return false;

    uint8 ch = (uint8)channel;
    if (ch >= (uint8)Channel::count) return false;

    if ((ctx.config.timNum == Num::TIM_16) || (ctx.config.timNum == Num::TIM_17)) {
        return channel == Channel::CH1;
    }

    return true;
}

volatile uint32* TIM::GetCcrReg(Channel channel)
{
    switch (channel) {
        case Channel::CH1: return &ctx.timReg_p->CCR1;
        case Channel::CH2: return &ctx.timReg_p->CCR2;
        case Channel::CH3: return &ctx.timReg_p->CCR3;
        case Channel::CH4: return &ctx.timReg_p->CCR4;
        default: return nullptr;
    }
}

void TIM::MainOutputEnable()
{
    // TIM1, TIM16 and TIM17 require BDTR.MOE for output compare/PWM pins.
    if ((ctx.config.timNum == Num::TIM_1) ||
        (ctx.config.timNum == Num::TIM_16) ||
        (ctx.config.timNum == Num::TIM_17)) {
        ctx.timReg_p->BDTR |= TIM_BDTR_MOE;
    }
}

void TIM::IrqHandlerClbk(Num timNum)
{
    TIM* timer_p = TIM::timer_p[(uint8)timNum];
    if (timer_p == nullptr) return;

    TIM_TypeDef* timReg_p = timer_p->ctx.timReg_p;

    if ((timReg_p->DIER & TIM_DIER_UIE) && (timReg_p->SR & TIM_SR_UIF)) {
        timReg_p->SR &= ~TIM_SR_UIF;

        if (timer_p->ctx.config.updateIrq.Clbk) {
            timer_p->ctx.config.updateIrq.Clbk(timNum);
        }
    }
}

