#include "irqAdc.h"

/******************************************************************************************************************************************
                                                         PRIVATE TYPES & VARIABLES
******************************************************************************************************************************************/
namespace hal::irqAdc {

IrqClbk_t AdcCallback = nullptr;

/******************************************************************************************************************************************
                                                                    API
******************************************************************************************************************************************/

Exec SetIrqClbk(IrqClbk_t Clbk)
{
    ASSERT(Clbk != nullptr, "Callback cannot be a nullpointer");
    AdcCallback = Clbk;
    return Exec::OK;
}

} // End of namespace 'hal::irqAdc'
/******************************************************************************************************************************************
                                                             INTERRUPT HANDLERS
******************************************************************************************************************************************/

#undef CODE_LABEL
#define CODE_LABEL  "IRQ ADC"

extern "C" {
    void ADC_IRQHandler();
}

void ADC_IRQHandler()
{
    if (hal::irqAdc::AdcCallback) {
        hal::irqAdc::AdcCallback();
    }
    else {
        REPORT_FAT("Invalid ADC IRQ callback!");
    }
}

