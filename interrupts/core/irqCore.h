/******************************************************************************************************************************************
                                                                PUBLIC TYPES
******************************************************************************************************************************************/
namespace hal::irq::core {

using SystickIrqClbk_t = void(*)(); // Systick timer interrupt callback
static SystickIrqClbk_t SystickIrqClbk;

/******************************************************************************************************************************************
                                                                    API
******************************************************************************************************************************************/

Exec SetSysTickIrqCallback(SystickIrqClbk_t Clbk)
{
    ASSERT(Clbk != nullptr, "SYSTICK INT CALLBACK");
    SystickIrqClbk = Clbk;
    return Exec::OK;
}

} // End of namespace 'hal::irq::core'
/******************************************************************************************************************************************
                                                             INTERRUPT HANDLERS
******************************************************************************************************************************************/

void NonMaskableInt_Handler()
{
    REPORT_FAT("NON MASKABLE INT OCCURED");
    NVIC_SystemReset();
}

void HardFault_Handler()
{
    REPORT_FAT("HARDFAULT HANDLER");
    NVIC_SystemReset();
}

void MemoryManagement_Handler()
{
    REPORT_FAT("MEMORY MANAGEMENT HANDLER");
    NVIC_SystemReset();
}

void BusFault_Handler()
{
    REPORT_FAT("BUS FAULT HANDLER");
    NVIC_SystemReset();
}

void UsageFault_Handler(void)
{
    REPORT_FAT("USAGE FAULT OCCURED");
    NVIC_SystemReset();
}

void SysTick_Handler()
{
    if (hal::irq::SystickIrqClbk != nullptr) hal::irq::SystickIrqClbk();
    else {
        REPORT_FAT("SYSTICK IRQ CALLBACK");
        NVIC_SystemReset();
    }
}

void WDT_Handler(void)
{
    REPORT_FAT("WATCHDOG TRIGGER");
    NVIC_SystemReset();
}

