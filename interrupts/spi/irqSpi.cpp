/******************************************************************************************************************************************
                                                         PRIVATE TYPES & VARIABLES
******************************************************************************************************************************************/
namespace hal::irqSpi {

static IrqClbk_t SpiClbkTab[hal::SPI_count];

/******************************************************************************************************************************************
                                                                    API
******************************************************************************************************************************************/

Exec SetIrqClbk(hal::spiNum_t spiNum, IrqClbk_t Clbk)
{
    ASSERT(Clbk != nullptr, "SPI%d IRQ CALLBACK", spiNum + 1);
    SpiClbkTab[spiNum] = Clbk;
    return Exec::OK;
}

} // End of namespace 'hal::irqSpi'
/******************************************************************************************************************************************
                                                             INTERRUPT HANDLERS
******************************************************************************************************************************************/

#undef CODE_LABEL
#define CODE_LABEL  "IRQ SPI"

extern "C" {
    void SPI1_IRQHandler();
    void SPI2_IRQHandler();
    void SUBGHZSPI_IRQHandler();
}

static void IrqErrHandler(int8 spiNum)
{
    REPORT_FAT("SPI%d IRQ CALLBACK", spiNum + 1);
}

void SPI1_IRQHandler()
{
    if (hal::irqSpi::SpiClbkTab[hal::SPI1]) {
        hal::irqSpi::SpiClbkTab[hal::SPI1](hal::SPI1);
    }
    else IrqErrHandler(hal::SPI1);
}

void SPI2_IRQHandler()
{
    if (hal::irqSpi::SpiClbkTab[hal::SPI2]) {
        hal::irqSpi::SpiClbkTab[hal::SPI2](hal::SPI2);
    }
    else IrqErrHandler(hal::SPI2);
}

void SUBGHZSPI_IRQHandler()
{
    if (hal::irqSpi::SpiClbkTab[hal::SPI3_RF]) {
        hal::irqSpi::SpiClbkTab[hal::SPI3_RF](hal::SPI3_RF);
    }
    else IrqErrHandler(hal::SPI3_RF);
}

